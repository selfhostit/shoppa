// Writes src/lib/icons.ts: the line icons items, sections and lists show,
// taken from Lucide (https://lucide.dev, ISC licence), plus a few drawn here
// in the same style for things Lucide has no icon for.
//
// Every icon the catalogue (backend/catalogue/generics.json) names is kept,
// and the extras below, so the icon picker has a few more to choose from. To
// add one, name it in the catalogue or in extras, then run, from web/:
//
//   npm pack lucide-static && tar xzf lucide-static-*.tgz
//   node scripts/icons.mjs package/icons
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [dir] = process.argv.slice(2);
if (!dir) {
  console.error('usage: node scripts/icons.mjs path/to/lucide-static/icons');
  process.exit(1);
}

// the kinds of list (lib/kinds.ts) and a few more to pick from
const extras = [
  'shopping-cart',
  'house',
  'gift',
  'heart',
  'star',
  'party-popper',
  'tree-pine',
  'mountain',
  'flower',
  'bike',
  'plane',
  'dumbbell',
  'puzzle',
  'baby',
  'pencil',
  'scissors',
  'music',
  'gamepad-2',
  'trophy',
  'paintbrush',
  'box',
  'briefcase',
  'school',
  'car',
  'truck',
  'leaf',
];

// in Lucide's style: 24×24, 2px round strokes
const own = {
  cheese:
    '<path d="M3 19.5V12l12-7.5 6 7.5v7.5z"/><path d="M3 12h18"/><circle cx="8" cy="16" r="1.5"/><circle cx="15.5" cy="15.5" r="1"/>',
  tomato: '<circle cx="12" cy="14" r="7.5"/><path d="M12 6.5V3"/><path d="M8.5 6.5 12 8.5l3.5-2"/>',
  onion:
    '<path d="M12 3c-1 2.5-7 5-7 10.5a7 7 0 0 0 14 0C19 8 13 5.5 12 3z"/><path d="M12 9c-2 2.5-2.5 5-2.5 10M12 9c2 2.5 2.5 5 2.5 10"/>',
  rug: '<rect x="4" y="6" width="16" height="12" rx="1"/><rect x="7.5" y="9" width="9" height="6" rx=".5"/><path d="M2 8.5h2M2 12h2M2 15.5h2M20 8.5h2M20 12h2M20 15.5h2"/>',
  curtains:
    '<path d="M2 3h20"/><path d="M4 3v18h4c1-5 2-9 3-18"/><path d="M20 3v18h-4c-1-5-2-9-3-18"/>',
  'dining-table': '<path d="M3 8h18"/><path d="M5 8v12M19 8v12"/><path d="M5 13h14"/>',
  wardrobe:
    '<rect x="4" y="2" width="16" height="18" rx="1"/><path d="M12 2v18"/><path d="M9.5 10v2M14.5 10v2"/><path d="M6 20v2M18 20v2"/>',
  drawers:
    '<rect x="4" y="3" width="16" height="16" rx="1"/><path d="M4 8.5h16M4 14h16"/><path d="M11 6h2M11 11.5h2M11 16.5h2"/><path d="M6 19v2M18 19v2"/>',
  hat: '<path d="M6 14V9a6 6 0 0 1 12 0v5"/><path d="M2 14h20c0 2-4 3.5-10 3.5S2 16 2 14z"/>',
  trousers: '<path d="M6 2h12l1 20h-5l-2-12-2 12H5z"/><path d="M6 6h12"/>',
};

const catalogue = JSON.parse(readFileSync('../backend/catalogue/generics.json', 'utf8'));
const names = new Set([
  ...catalogue.sections.map((s) => s.icon),
  ...catalogue.items.map((i) => i.icon),
  ...extras,
]);
const icons = {};
for (const name of [...names].filter(Boolean).sort()) {
  if (own[name]) {
    icons[name] = own[name];
    continue;
  }
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  icons[name] = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>');
}
const body = Object.entries(icons)
  .map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`)
  .join('\n');
writeFileSync(
  'src/lib/icons.ts',
  `// Generated by scripts/icons.mjs: line icons from Lucide (https://lucide.dev,
// ISC licence, © Lucide Icons and Contributors), and a few drawn for Shoppa.
// Each is the inside of a 24×24 <svg> with 2px round strokes.
export const icons: Record<string, string> = {
${body}
};
`,
);
console.log(`${Object.keys(icons).length} icons`);
